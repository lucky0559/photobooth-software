#!/usr/bin/env node
// Copies packages/core/src/*.ts into supabase/functions/_shared/core/ so Edge Functions can import @pb/core.
//
// Why a copy: `supabase functions serve` (and the deploy bundler) only see files under supabase/functions, so an
// import map entry pointing at ../../packages/core fails with "Module not found" at worker boot. The copy is
// gitignored; run this before `supabase functions serve` or `supabase functions deploy` (the integration runner
// runs it for you). Usage: node scripts/sync-core-to-functions.mjs
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'packages', 'core', 'src');
const dest = join(root, 'supabase', 'functions', '_shared', 'core');

rmSync(dest, { recursive: true, force: true });
mkdirSync(dest, { recursive: true });

const files = readdirSync(src).filter((f) => f.endsWith('.ts'));
for (const f of files) {
  const banner = `// GENERATED by scripts/sync-core-to-functions.mjs from packages/core/src/${f}. Do not edit.\n`;
  writeFileSync(join(dest, f), banner + readFileSync(join(src, f), 'utf8'));
}
console.log(`synced ${files.length} files from packages/core/src to supabase/functions/_shared/core`);
